import { defineConfig, loadEnv } from 'vite';
import { checker } from 'vite-plugin-checker';
import { VitePWA, VitePWAOptions } from 'vite-plugin-pwa';
import react from '@vitejs/plugin-react-swc';
import svgrPlugin from 'vite-plugin-svgr';
import { z } from 'zod';
import jwt from 'jsonwebtoken';
const preInitEnvSchema = z.object({
    MAPKIT_JS_TEAM_ID: z.string(),
    MAPKIT_JS_KEY_ID: z.string(),
    MAPKIT_JS_AUTH_KEY: z.string(),
    MAPKIT_JS_TTL: z.coerce.number().default(31_536_000), // 1 year
    MAPKIT_ALLOWED_ORIGINS: z.string().default(''),
});

// kennel hack for pr preview deployments
const PROJECT_NAME = 'eats';
const WEB_SERVICE_NAME = 'web';
const API_SERVICE_NAME = 'api';
// when VITE_API_URL is set to be this, use the slop generated by kennel
const AUTO_API_URL = 'kennel-makes-my-life-worse';

function apiUrlFromAppUrl(appUrl: string): string | undefined {
    try {
        const url = new URL(appUrl);
        const prefix = `${PROJECT_NAME}-${WEB_SERVICE_NAME}-`;
        if (!url.hostname.startsWith(prefix)) return undefined;
        url.hostname = `${PROJECT_NAME}-${API_SERVICE_NAME}-${url.hostname.slice(prefix.length)}`;
        return url.origin;
    } catch {
        return undefined;
    }
}

const manifestForPlugin: Partial<VitePWAOptions> = {
    registerType: 'prompt',
    includeAssets: ['favicon.ico', '/favicons/apple-touch-icon.png'],
    manifest: {
        short_name: 'CMUEats',
        name: 'CMUEats',
        icons: [
            {
                src: '/favicons/android-chrome-192x192.png',
                type: 'image/png',
                sizes: '192x192',
                purpose: 'any',
            },
            {
                src: '/favicons/android-chrome-512x512.png',
                type: 'image/png',
                sizes: '512x512',
                purpose: 'any',
            },
            {
                src: '/favicons/android-chrome-192x192-maskable.png',
                type: 'image/png',
                sizes: '192x192',
                purpose: 'maskable',
            },
            {
                src: '/favicons/android-chrome-512x512-maskable.png',
                type: 'image/png',
                sizes: '512x512',
                purpose: 'maskable',
            },
        ],
        scope: '/',
        start_url: '/',
        display: 'standalone',
        theme_color: '#ffffff',
        background_color: '#ffffff',
    },
};

export default defineConfig(({ mode }) => {
    const loadedEnv = loadEnv(mode, process.cwd(), '');
    const parsedResult = preInitEnvSchema.safeParse(loadedEnv);
    if (parsedResult.error) {
        console.error(
            'Missing one or more .env variables! Make sure you have a .env file locally.',
            parsedResult.error,
        );
        process.exit(1);
    }
    const env = parsedResult.data;

    const appUrl = process.env.APP_URL;
    const envApiUrl = loadedEnv.VITE_API_URL;

    if (envApiUrl === AUTO_API_URL) {
        if (!appUrl) {
            console.error(
                `Missing APP_URL! VITE_API_URL is ${AUTO_API_URL}, but APP_URL is unset.` +
                    'APP_URL is only available in kennel builds. Make sure you have set the local .env correctly.',
            );
            process.exit(1);
        }

        const derivedApiUrl = apiUrlFromAppUrl(appUrl);
        if (!derivedApiUrl) {
            console.error(
                `VITE_API_URL is "${AUTO_API_URL}", but APP_URL ("${appUrl}") does not look like ` +
                    `a kennel site URL (expected "${PROJECT_NAME}-${WEB_SERVICE_NAME}-<branch>.<domain>").`,
            );
            process.exit(1);
        }

        process.env.VITE_API_URL = derivedApiUrl;
    }

    const iat = Date.now() / 1000;
    // configured origins + this deployment's site, normalized and de-duplicated
    const mapkitOrigin = [
        ...new Set(
            `${env.MAPKIT_ALLOWED_ORIGINS},${appUrl ?? ''}`
                .split(',')
                .map((value) => value.trim())
                .filter((value) => /^https?:\/\//.test(value))
                .map((value) => new URL(value).origin),
        ),
    ].join(',');

    const payload = {
        iat,
        exp: iat + env.MAPKIT_JS_TTL,
        iss: env.MAPKIT_JS_TEAM_ID,
        origin: mapkitOrigin,
    };

    const header = {
        typ: 'JWT',
        alg: 'ES256',
        kid: env.MAPKIT_JS_KEY_ID,
    };

    try {
        const token = jwt.sign(payload, atob(env.MAPKIT_JS_AUTH_KEY), { header });
        // eslint-disable-next-line no-console
        console.info({
            title: 'MapKit JS token generated successfully',
            summary: `Origin: ${mapkitOrigin}, expires in ${env.MAPKIT_JS_TTL} seconds.`,
            text: `process.env.VITE_AUTO_GENERATED_MAPKITJS_TOKEN = '${token}';`,
        });
        process.env.VITE_AUTO_GENERATED_MAPKITJS_TOKEN = token;
    } catch (error) {
        console.error(error);
        process.exit(1);
    }

    return {
        plugins: [
            react(),
            svgrPlugin(),
            VitePWA({
                // WARNING! Removing this library means that all clients with the VitePWA service worker installed *will never have it uninstalled*. (see https://github.com/ScottyLabs/cmueats/pull/642 for more details)
                manifest: manifestForPlugin,
                registerType: 'autoUpdate',
                // Enables autoupdate (uses new version after user quits and reloads app)
                workbox: {
                    cleanupOutdatedCaches: true,
                    skipWaiting: true,
                },
                selfDestroying: true, // remove previously-registered service worker (if it exists)
            }),
            checker({
                typescript: true,
            }),
        ],
        build: {
            rollupOptions: {
                external: ['jsonwebtoken'],
            },
        },
        logLevel: 'info',
    };
});
